import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "jsr:@supabase/supabase-js@2";

const RESEND_KEY  = Deno.env.get("RESEND_API_KEY") ?? "";
const FROM        = Deno.env.get("RESEND_FROM") ?? "onboarding@resend.dev";

const supabaseAdmin = createClient(
  Deno.env.get("SUPABASE_URL")!,
  Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!
);

const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: CORS });

  try {
    const { type, ...p } = await req.json();
    const lang = String(p.lang || "fr") === "en" ? "en" : "fr";
    let payload;

    if (type === "results") {
      const subject = lang === "en"
        ? `Results — ${p.exam_title}`
        : `Résultats — ${p.exam_title}`;
      payload = { from: FROM, to: [p.to_email], subject, html: resultsHtml(p, lang) };
    } else if (type === "retake") {
      const subject = lang === "en"
        ? `Exam link — ${p.exam_title}`
        : `Lien de reprise — ${p.exam_title}`;
      payload = { from: FROM, to: [p.to_email], subject, html: retakeHtml(p, lang) };
    } else if (type === "invite") {
      const subject = lang === "en"
        ? `Exam invitation — ${p.exam_title}`
        : `Invitation à l'examen — ${p.exam_title}`;
      payload = { from: FROM, to: [p.to_email], subject, html: inviteHtml(p, lang) };
      if (p.reply_to) payload.reply_to = p.reply_to;
    } else if (type === "ticket") {
      payload = {
        from: FROM,
        to: [p.to_email as string],
        subject: String(p.subject || `New ticket from ${p.teacher_name}`),
        html: ticketHtml(p as Record<string, string>),
      };
    } else {
      return respond({ error: "Unknown type" }, 400);
    }

    const r = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${RESEND_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });

    const data = await r.json();

    if (r.ok) {
      // Fire-and-forget log — never block the response
      supabaseAdmin.from("email_logs").insert({
        type,
        to_email:   p.to_email   || null,
        exam_id:    p.exam_id    || null,
        attempt_id: p.attempt_id || null,
        teacher_id: p.teacher_id || null,
        resend_id:  data.id      || null,
        status:     "sent",
      }).then(() => {}).catch(() => {});
    }

    return respond(r.ok ? { id: data.id } : { error: data }, r.ok ? 200 : r.status);
  } catch (e) {
    return respond({ error: String(e) }, 500);
  }
});

function respond(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS, "Content-Type": "application/json" },
  });
}

